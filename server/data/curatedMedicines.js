export function findCuratedMedicine(query) {
  if (!query || typeof query !== 'string') {
    return CURATED_MEDICINES;
  }
  const q = query.trim().toLowerCase();
  if (!q) return CURATED_MEDICINES;

  return CURATED_MEDICINES.filter(med => {
    return (
      med.id.toLowerCase().includes(q) ||
      med.name.toLowerCase().includes(q) ||
      med.nameUrdu.includes(q) ||
      med.genericName.toLowerCase().includes(q) ||
      med.genericNameUrdu.includes(q) ||
      med.category.toLowerCase().includes(q) ||
      med.categoryUrdu.includes(q) ||
      med.manufacturer.toLowerCase().includes(q) ||
      (med.drapRegNo && med.drapRegNo.includes(q))
    );
  });
}
